class Product {
  final String id;
  final String name;
  final String brand;
  final String model;
  final int stock;
  final double price;
  final String imageUrl;

  Product({
    required this.id,
    required this.name,
    required this.brand,
    required this.model,
    required this.stock,
    required this.price,
    required this.imageUrl,
  });
}